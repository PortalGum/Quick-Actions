    static final String[] PALETTE = circleHalf(11);

    private static String[] circleHalf(int size) {
        String[] rows = new String[size];
        double c = (size - 1) / 2.0;
        for (int y = 0; y < size; y++) {
            StringBuilder row = new StringBuilder();
            for (int x = 0; x < size; x++) {
                double d = Math.sqrt((x - c) * (x - c) + (y - c) * (y - c));
                boolean ring = d <= c + 0.5 && d >= c - 0.9;
                boolean half = x > c && d <= c + 0.5;
                row.append(ring || half ? '#' : '.');
            }
            rows[y] = row.toString();
        }
        return rows;
    }

